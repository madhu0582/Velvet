import { useState } from 'react';
import { useToast } from '../context/ToastContext';

export default function RequestMoreInfo({ email, onClose }) {
  const { showToast } = useToast();
  const [sent, setSent] = useState(false);

  // Determine missing fields based on NLP extraction
  const getMissingFields = () => {
    const missing = [];
    if (!email.nlp.material || email.nlp.material === '—') missing.push('Material Number');
    if (!email.nlp.qty || email.nlp.qty === '—') missing.push('Quantity');
    if (!email.nlp.po || email.nlp.po === '—') missing.push('PO / Reference Number');
    if (parseInt(email.nlp.confidence) < 90) missing.push('Clear request type (Adjustment / Transfer / Batch)');
    // Always add some for demo purposes
    if (missing.length === 0) {
      missing.push('Batch Number', 'Total Cost for approval routing');
    }
    return missing;
  };

  const missingFields = getMissingFields();

  const generateEmailTemplate = () => {
    return `Dear ${email.sender.split('<')[0].trim()},

Thank you for your request regarding ${email.nlp.material || 'the material'} at ${email.nlp.vendor || 'your plant'}.

We have reviewed your email but require the following additional information to proceed:

${missingFields.map((f, i) => `${i + 1}. ${f}`).join('\n')}

Could you please provide the above details so we can process your request?

If applicable, please also attach:
• Inventory Transaction Form (Help Out Form) with all fields completed
• Supporting documents (packing list, screenshot of portal error, etc.)

We will process your request within 24 hours of receiving the complete information.

Best regards,
${email.nlp.vendor?.includes('Korea') || email.nlp.vendor?.includes('China') || email.nlp.vendor?.includes('Japan') ? 'Chris Wang\nTPM Inventory Analyst — APAC' : 'Anna Polkowska\nTPM Inventory Analyst — EMEA'}
The Estée Lauder Companies
(Auto-generated by SynOps)`;
  };

  const handleSend = () => {
    setSent(true);
    showToast('Clarification email sent to ' + email.sender);
  };

  return (
    <div style={{ position: 'fixed', top: 0, left: 0, right: 0, bottom: 0, background: 'rgba(0,0,0,0.5)', display: 'flex', alignItems: 'center', justifyContent: 'center', zIndex: 1000 }} onClick={onClose}>
      <div style={{ background: 'white', borderRadius: '12px', width: '800px', maxHeight: '88vh', overflow: 'auto', boxShadow: '0 20px 60px rgba(0,0,0,0.3)' }} onClick={e => e.stopPropagation()}>

        {/* Header */}
        <div style={{ padding: '18px 24px', borderBottom: '1px solid #e2e8f0', display: 'flex', alignItems: 'center', justifyContent: 'space-between' }}>
          <div>
            <h2 style={{ fontSize: '16px', color: '#1e293b', margin: 0 }}>📧 Request More Information</h2>
            <p style={{ fontSize: '12px', color: '#64748b', margin: '4px 0 0' }}>Missing details identified — requesting clarification from sender</p>
          </div>
          <button onClick={onClose} style={{ background: 'none', border: 'none', fontSize: '20px', cursor: 'pointer', color: '#94a3b8' }}>×</button>
        </div>

        <div style={{ padding: '24px' }}>

          {/* NLP Analysis - Missing Fields */}
          <div style={{ background: '#fef3c7', borderRadius: '8px', padding: '14px 18px', marginBottom: '20px', border: '1px solid #fcd34d' }}>
            <div style={{ fontSize: '12px', fontWeight: 700, color: '#92400e', marginBottom: '10px' }}>⚠ Missing Information</div>
            <div style={{ display: 'flex', flexWrap: 'wrap', gap: '8px' }}>
              {missingFields.map((field, i) => (
                <span key={i} style={{ background: 'white', border: '1px solid #f59e0b', borderRadius: '6px', padding: '4px 12px', fontSize: '12px', fontWeight: 600, color: '#92400e' }}>
                  ❌ {field}
                </span>
              ))}
            </div>
          </div>

          {/* Original Email Thread */}
          <div style={{ marginBottom: '20px' }}>
            <div style={{ fontSize: '12px', fontWeight: 700, color: '#1e293b', marginBottom: '10px' }}>📨 Original Email Thread</div>
            <div style={{ background: '#f8fafc', borderRadius: '8px', border: '1px solid #e2e8f0', padding: '16px' }}>
              <div style={{ marginBottom: '12px', paddingBottom: '12px', borderBottom: '1px solid #e2e8f0' }}>
                <div style={{ display: 'flex', justifyContent: 'space-between', marginBottom: '4px' }}>
                  <span style={{ fontSize: '12px', fontWeight: 700, color: '#1e293b' }}>{email.sender}</span>
                  <span style={{ fontSize: '11px', color: '#94a3b8' }}>{email.date}</span>
                </div>
                <div style={{ fontSize: '12px', fontWeight: 600, color: '#475569', marginBottom: '8px' }}>Subject: {email.subject}</div>
                <div style={{ fontSize: '12.5px', color: '#475569', lineHeight: '1.7', whiteSpace: 'pre-wrap', background: 'white', padding: '12px', borderRadius: '6px', border: '1px solid #e2e8f0' }}>
                  {email.body}
                </div>
              </div>

              {/* NLP Extracted Fields (what we got) */}
              <div style={{ fontSize: '11px', color: '#64748b' }}>
                <strong>NLP Extracted:</strong> Material: {email.nlp.material} | Qty: {email.nlp.qty} | Vendor: {email.nlp.vendor} | PO: {email.nlp.po} | Confidence: {email.nlp.confidence}
              </div>
            </div>
          </div>

          {/* Response Email Template */}
          <div style={{ marginBottom: '20px' }}>
            <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '10px' }}>
              <div style={{ fontSize: '12px', fontWeight: 700, color: '#1e293b' }}>✉️ Clarification Email — Auto-Generated Template</div>
              {sent && <span style={{ background: '#d1fae5', color: '#065f46', padding: '3px 10px', borderRadius: '10px', fontSize: '11px', fontWeight: 700 }}>✓ Sent</span>}
            </div>

            <div style={{ background: 'white', borderRadius: '8px', border: '1px solid #e2e8f0', overflow: 'hidden' }}>
              {/* Email Header */}
              <div style={{ padding: '12px 16px', background: '#f1f5f9', borderBottom: '1px solid #e2e8f0' }}>
                <table style={{ width: '100%', fontSize: '12px' }}>
                  <tbody>
                    <tr><td style={{ fontWeight: 600, width: '50px', color: '#64748b', padding: '3px 0' }}>To:</td><td style={{ color: '#1e293b' }}>{email.sender}</td></tr>
                    <tr><td style={{ fontWeight: 600, color: '#64748b', padding: '3px 0' }}>CC:</td><td style={{ color: '#1e293b' }}>tpm.inventory@elcompanies.com</td></tr>
                    <tr><td style={{ fontWeight: 600, color: '#64748b', padding: '3px 0' }}>Subject:</td><td style={{ color: '#1e293b', fontWeight: 600 }}>RE: {email.subject} — Additional Information Required</td></tr>
                  </tbody>
                </table>
              </div>

              {/* Email Body */}
              <div style={{ padding: '16px', fontSize: '12.5px', color: '#475569', lineHeight: '1.8', whiteSpace: 'pre-wrap' }}>
                {generateEmailTemplate()}
              </div>
            </div>
          </div>

          {/* Tracking Info */}
          {sent && (
            <div style={{ background: '#ecfdf5', borderRadius: '8px', padding: '14px 18px', marginBottom: '20px', border: '1px solid #a7f3d0' }}>
              <div style={{ fontSize: '12px', fontWeight: 700, color: '#065f46', marginBottom: '8px' }}>✓ Email Sent — Tracking Active</div>
              <div style={{ fontSize: '12px', color: '#047857' }}>
                • Sent to: {email.sender} at {new Date().toLocaleTimeString()}<br/>
                • SLA: 24 hours for response<br/>
                • Auto-reminder will be sent if no reply within 48 hours<br/>
                • Work Item status updated to: "Awaiting Vendor Response"
              </div>
            </div>
          )}

          {/* Actions */}
          <div style={{ display: 'flex', gap: '10px', justifyContent: 'flex-end', paddingTop: '16px', borderTop: '1px solid #e2e8f0' }}>
            <button className="btn btn-secondary" onClick={onClose}>Close</button>
            {!sent && (
              <button className="btn btn-primary" onClick={handleSend} style={{ padding: '10px 24px' }}>
                📤 Send Clarification Request
              </button>
            )}
            {sent && (
              <button className="btn btn-success" onClick={onClose} style={{ padding: '10px 24px' }}>
                ✓ Done — Awaiting Response
              </button>
            )}
          </div>
        </div>
      </div>
    </div>
  );
}
